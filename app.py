class PostgresConnection:
    """Tiny compatibility adapter: original app uses SQLite's ? placeholders."""
    def __init__(self, underlying):
        self.underlying = underlying

    def execute(self, sql, params=None):
        return self.underlying.execute(sql.replace('?', '%s'), params or ())

    def executescript(self, script):
        # Schema contains no procedural bodies or semicolons in literals.
        for statement in script.split(';'):
            if statement.strip():
                self.execute(statement)

@contextmanager
def conn():
    if USE_POSTGRES:
        with psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10) as d:
            yield PostgresConnection(d)
    else:
        d = sqlite3.connect(DB_FILE, timeout=30)
        d.row_factory = sqlite3.Row
        d.execute('PRAGMA foreign_keys = ON')
        d.execute('PRAGMA busy_timeout = 30000')
        try:
            yield d
            d.commit()
        except:
            d.rollback()
            raise
        finally:
            d.close()

