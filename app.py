# Circle method, supports odd participant counts and return legs.
def round_robin(team_ids, double=False):
    arr=list(team_ids)
    if len(arr)%2:arr.append(None)
    n=len(arr)
    if n<2:return []
    out=[]
    for rnd in range(n-1):
        for i in range(n//2):
            a,b=arr[i],arr[n-i-1]
            if a is not None and b is not None:
                if (rnd+i)%2:a,b=b,a
                out.append((rnd+1,a,b))
        arr=[arr[0]]+[arr[-1]]+arr[1:-1]
    if double:
        out += [(r+n-1,b,a) for r,a,b in list(out)]
    return out

def ko_label(round_no,num_rounds):
    distance=num_rounds-round_no
    return {0:'Finale',1:'Halbfinale',2:'Viertelfinale',3:'Achtelfinale',4:'Sechzehntelfinale'}.get(distance,'K.-o.-Runde')

def make_bracket(d, teams):
    n=len(teams)
    if n<2:raise HTTPException(400,'Für die K.-o.-Phase sind mindestens 2 Vereine nötig.')
    if n>32:raise HTTPException(400,'Maximal 32 Vereine im Turnierbaum.')
    size=2**math.ceil(math.log2(n))
    padded=list(teams)+[None]*(size-n)
    rounds=int(math.log2(size))
    previous=[]
    for r in range(1,rounds+1):
        current=[]
        count=size//(2**r)
        for slot in range(count):
            if r==1:
                a,b=padded[slot],padded[size-slot-1]
                cur=d.execute('INSERT INTO matches(stage,round_no,slot,home_id,away_id,winner_id,label) VALUES (?,?,?,?,?,?,?) RETURNING id',
                              ('ko',r,slot+1,a,b,a if (a and not b) else b if (b and not a) else None,ko_label(r,rounds)))
            else:
                fa,fb=previous[slot*2],previous[slot*2+1]
                cur=d.execute('INSERT INTO matches(stage,round_no,slot,feeder_home,feeder_away,label) VALUES (?,?,?,?,?,?) RETURNING id',
                              ('ko',r,slot+1,fa,fb,ko_label(r,rounds)))
            current.append(cur.fetchone()['id'])
        previous=current
    propagate(d)

def propagate(d):
    games=d.execute("SELECT * FROM matches WHERE stage='ko' ORDER BY round_no,slot").fetchall()
    winners={}
    for m in games:
        a=m['home_id'] if m['feeder_home'] is None else winners.get(m['feeder_home'])
        b=m['away_id'] if m['feeder_away'] is None else winners.get(m['feeder_away'])
        changed=a!=m['home_id'] or b!=m['away_id']
        if changed:
            d.execute('UPDATE matches SET home_id=?,away_id=?,home_score=NULL,away_score=NULL,winner_id=NULL WHERE id=?',(a,b,m['id']))
        old_winner=None if changed else m['winner_id']
        if m['feeder_home'] is None and m['feeder_away'] is None and ((a and not b) or (b and not a)):
            winner=a or b
            if winner!=old_winner:d.execute('UPDATE matches SET winner_id=? WHERE id=?',(winner,m['id']))
        else: winner=old_winner
        winners[m['id']]=winner

@app.post('/api/admin/generate')
def generate(request:Request):
    with conn() as d:
        require_admin(request,d)
        if d.execute('SELECT 1 FROM matches LIMIT 1').fetchone():raise HTTPException(409,'Es gibt bereits einen Spielplan.')
        c=d.execute('SELECT * FROM cup WHERE id=1').fetchone()
        teams=[x['club_id'] for x in d.execute('SELECT club_id FROM participants ORDER BY joined_at,club_id')]
        if len(teams)<2:raise HTTPException(400,'Mindestens zwei Vereine notwendig.')
        if c['format']=='knockout':make_bracket(d,teams)
        elif c['format']=='league':
            for slot,(r,a,b) in enumerate(round_robin(teams,bool(c['double_round'])),1):
                d.execute('INSERT INTO matches(stage,round_no,slot,home_id,away_id,label) VALUES (?,?,?,?,?,?)',
                          ('league',r,slot,a,b,'Spieltag '+str(r)))
        else:
            count=c['group_count']
            if len(teams)<count*2:raise HTTPException(400,f'Für {count} Gruppen brauchst du mindestens {count*2} Vereine.')
            groups=[[] for _ in range(count)]
            for i,club in enumerate(teams):
                row=i//count
                position=i%count if row%2==0 else count-1-(i%count)
                groups[position].append(club)
            if any(len(group)<c['qualifiers'] for group in groups):raise HTTPException(400,'Zu viele Qualifikationsplätze.')
            if count*c['qualifiers'] not in (2,4,8,16):raise HTTPException(400,'Qualifikationsplätze müssen einen gültigen K.-o.-Baum ergeben.')
            for g,group in enumerate(groups,1):
                for slot,(r,a,b) in enumerate(round_robin(group,bool(c['double_round'])),1):
                    d.execute('INSERT INTO matches(stage,group_no,round_no,slot,home_id,away_id,label) VALUES (?,?,?,?,?,?,?)',
                              ('group',g,r,slot,a,b,'Gruppe '+chr(64+g)))
        d.execute("UPDATE cup SET status='geschlossen' WHERE id=1")
        return {'ok':True}

@app.post('/api/admin/ko/start')
def start_ko(request:Request):
    with conn() as d:
        require_admin(request,d)
        c=d.execute('SELECT * FROM cup WHERE id=1').fetchone()
        if c['format']!='groups':raise HTTPException(400,'Nur nach einer Gruppenphase möglich.')
        if d.execute("SELECT 1 FROM matches WHERE stage='ko' LIMIT 1").fetchone():raise HTTPException(409,'K.-o.-Phase läuft bereits.')
        groupmatches=d.execute("SELECT * FROM matches WHERE stage='group'").fetchall()
        if not groupmatches or any(m['home_score'] is None for m in groupmatches):raise HTTPException(400,'Zuerst alle Gruppenspiele abschliessen.')
        groups=[standings(d,'group',g) for g in range(1,c['group_count']+1)]
        if any(len(g)<c['qualifiers'] for g in groups):raise HTTPException(400,'Zu wenige Vereine in einer Gruppe.')
        # Seed winners first, then runners from reversed group order; avoid same-group first-round pairings where possible.
        if c['qualifiers']==2:
            winners=[group[0]['id'] for group in groups]
            runners=[group[1]['id'] for group in groups]
            # Bracket generation pairs left and mirrored right -> winners play runners from other groups.
            # For two groups, mirrored indices yield A1-B2, B1-A2.
            opponents=runners[1:]+runners[:1]
            teams=winners+list(reversed(opponents))
        else:teams=[group[0]['id'] for group in groups]
        make_bracket(d,teams)
        return {'ok':True}

@app.post('/api/matches/{match_id}/score')
def score(match_id:int,body:Score,request:Request):
    with conn() as d:
        u=require_user(request,d)
        m=d.execute('SELECT * FROM matches WHERE id=?',(match_id,)).fetchone()
        if not m:raise HTTPException(404,'Spiel nicht gefunden.')
        if not (u['is_admin'] or u['club_id'] in (m['home_id'],m['away_id'])):raise HTTPException(403,'Du darfst nur eigene Spiele eintragen.')
        if not m['home_id'] or not m['away_id']:raise HTTPException(409,'Die Begegnung steht noch nicht fest.')
        if (body.home_score is None) != (body.away_score is None):raise HTTPException(400,'Bitte beide Resultate eintragen.')
        if body.home_score is not None and (body.home_score<0 or body.away_score<0 or body.home_score>99 or body.away_score>99):raise HTTPException(400,'Resultat muss zwischen 0 und 99 liegen.')
        winner=None
        if body.home_score is not None and m['stage']=='ko':
            if body.home_score>body.away_score:winner=m['home_id']
            elif body.away_score>body.home_score:winner=m['away_id']
            else:
                if body.winner_id not in (m['home_id'],m['away_id']):raise HTTPException(400,'Bei Gleichstand bitte Sieger nach Penaltyschiessen auswählen.')
                winner=body.winner_id
        old={'home_score':m['home_score'],'away_score':m['away_score'],'winner_id':m['winner_id']}
        d.execute('UPDATE matches SET home_score=?,away_score=?,winner_id=? WHERE id=?',
                  (body.home_score,body.away_score,winner,match_id))
        d.execute('INSERT INTO audit(match_id,actor,previous,updated,created_at) VALUES (?,?,?,?,?)',
                  (match_id,'Admin' if u['is_admin'] else 'Verein '+str(u['club_id']),json.dumps(old),json.dumps(body.model_dump()),now()))
        if m['stage']=='ko':propagate(d)
        return {'ok':True}

