# Small-process abuse throttling (for larger public sites, use a shared rate limiter).
_rate_hits = {}
def rate_limit(request: Request, kind: str, max_attempts: int, seconds: int):
    ip = request.client.host if request.client else 'unknown'
    key = (ip,kind)
    t = time.monotonic()
    attempts = [v for v in _rate_hits.get(key, []) if t-v < seconds]
    if len(attempts) >= max_attempts:
        raise HTTPException(429, 'Zu viele Versuche. Bitte später erneut versuchen.')
    attempts.append(t)
    _rate_hits[key] = attempts
    # Prevent unbounded growth in very long running processes.
    if len(_rate_hits)>5000:
        for k,v in list(_rate_hits.items()):
            if not v or t-v[-1]>3600:_rate_hits.pop(k,None)

