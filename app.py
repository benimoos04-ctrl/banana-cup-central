def standings(d, stage, group_no=None):
    cup=d.execute('SELECT * FROM cup WHERE id=1').fetchone()
    rows=d.execute('''SELECT c.id,c.name,c.tag,c.color FROM clubs c JOIN participants p ON p.club_id=c.id ORDER BY c.name''').fetchall()
    stats={r['id']:{**dict(r),'played':0,'wins':0,'draws':0,'losses':0,'gf':0,'ga':0,'gd':0,'points':0} for r in rows}
    if stage=='group':
        ids=[r['home_id'] for r in d.execute('SELECT DISTINCT home_id FROM matches WHERE stage=? AND group_no=? AND home_id IS NOT NULL',('group',group_no)).fetchall()]
        ids += [r['away_id'] for r in d.execute('SELECT DISTINCT away_id FROM matches WHERE stage=? AND group_no=? AND away_id IS NOT NULL',('group',group_no)).fetchall()]
        stats={k:v for k,v in stats.items() if k in set(ids)}
        games=d.execute('SELECT * FROM matches WHERE stage=? AND group_no=? AND home_score IS NOT NULL AND away_score IS NOT NULL',('group',group_no)).fetchall()
    else:
        games=d.execute('SELECT * FROM matches WHERE stage=? AND home_score IS NOT NULL AND away_score IS NOT NULL',('league',)).fetchall()
    for m in games:
        h,a=stats.get(m['home_id']),stats.get(m['away_id'])
        if not h or not a: continue
        hs,as_=m['home_score'],m['away_score']
        h['played']+=1;a['played']+=1;h['gf']+=hs;h['ga']+=as_;a['gf']+=as_;a['ga']+=hs
        if hs>as_: h['wins']+=1;h['points']+=3;a['losses']+=1
        elif hs<as_: a['wins']+=1;a['points']+=3;h['losses']+=1
        else: h['draws']+=1;a['draws']+=1;h['points']+=1;a['points']+=1
    for s in stats.values():s['gd']=s['gf']-s['ga']
    ordered=sorted(stats.values(),key=lambda x:(-x['points'],-x['gd'],-x['gf'],x['name'].lower()))
    for i,s in enumerate(ordered):s['rank']=i+1
    return ordered

def full_state(request,d):
    cup=obj(d.execute('SELECT * FROM cup WHERE id=1').fetchone())
    clubs=[]
    for r in d.execute('SELECT c.id,c.name,c.tag,c.color,c.players FROM clubs c JOIN participants p ON p.club_id=c.id ORDER BY c.name').fetchall():
        item=dict(r);item['players']=json.loads(item['players']);clubs.append(item)
    matches=[dict(x) for x in d.execute('SELECT * FROM matches ORDER BY CASE stage WHEN \'group\' THEN 0 WHEN \'league\' THEN 0 ELSE 1 END,round_no,group_no,slot,id').fetchall()]
    tables={}
    if cup['format']=='groups':
        for g in range(1,cup['group_count']+1):
            table=standings(d,'group',g)
            if table:tables['Gruppe '+chr(64+g)]=table
    elif cup['format']=='league':tables['Gesamttabelle']=standings(d,'league')
    u=user_for(request,d)
    myclub=next((x for x in clubs if u and x['id']==u['club_id']),None)
    if u and u['club_id'] and not myclub:
        r=d.execute('SELECT id,name,tag,color,players FROM clubs WHERE id=?',(u['club_id'],)).fetchone()
        if r:myclub=dict(r);myclub['players']=json.loads(myclub['players'])
    return {'cup':cup,'clubs':clubs,'matches':matches,'tables':tables,
            'me':{'club':myclub,'admin':bool(u['is_admin']) if u else False,'logged_in':bool(u)},
            'generated':bool(matches),'can_start_ko': cup['format']=='groups' and bool(d.execute("SELECT 1 FROM matches WHERE stage='group' LIMIT 1").fetchone()) and not bool(d.execute("SELECT 1 FROM matches WHERE stage='ko' LIMIT 1").fetchone())}

