def now(): return int(time.time())

def make_hash(password: str) -> str:
    salt = secrets.token_bytes(16)
    result = hashlib.pbkdf2_hmac('sha256', password.encode(), salt, 310000)
    return salt.hex() + ':' + result.hex()

def password_ok(password: str, stored: str) -> bool:
    try:
        salt, hashed = stored.split(':')
        check = hashlib.pbkdf2_hmac('sha256',password.encode(),bytes.fromhex(salt),310000)
        return hmac.compare_digest(check, bytes.fromhex(hashed))
    except (ValueError, TypeError): return False

def user_for(request: Request, d):
    token = request.cookies.get('banana_session','')
    if not token: return None
    row = d.execute('SELECT * FROM sessions WHERE token_hash=? AND expires>?',(hashlib.sha256(token.encode()).hexdigest(),now())).fetchone()
    if not row: return None
    return {'club_id':row['club_id'],'is_admin':bool(row['is_admin'])}

def require_user(request,d):
    u=user_for(request,d)
    if not u: raise HTTPException(401, 'Bitte zuerst anmelden.')
    return u

def require_admin(request,d):
    u=require_user(request,d)
    if not u['is_admin']: raise HTTPException(403,'Nur die Turnierleitung darf das ändern.')
    return u

def issue_cookie(response, d, club_id=None, admin=False, request=None):
    token = secrets.token_urlsafe(36)
    d.execute('INSERT INTO sessions(token_hash,club_id,is_admin,expires) VALUES (?,?,?,?)',
              (hashlib.sha256(token.encode()).hexdigest(),club_id,1 if admin else 0,now()+60*60*24*30))
    secure = request is not None and (request.url.scheme=='https' or request.headers.get('x-forwarded-proto')=='https')
    response.set_cookie('banana_session',token,max_age=60*60*24*30,httponly=True,samesite='lax',secure=secure,path='/')

